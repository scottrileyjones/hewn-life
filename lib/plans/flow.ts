/**
 * The growth-plan lifecycle:
 *
 *   form → startPlan → deck written → review email to us
 *        → approvePlan (one tap) → plan email to the lead (invite, booked or checkout)
 *        → follow-up after three days unless they book, pay or unsubscribe.
 *
 * Set PLAN_AUTO_SEND=true to skip the review step.
 */
import type { LeadInput } from './deck'
import { generateDeck } from './generate'
import { createPlan, dueFollowUps, findByToken, findLatestByEmail, plansConfigured, updatePlan, type PlanRecord, type Variant } from './store'
import { emailConfigured, sendFollowUp, sendPlanEmail, sendReview } from './email'
import { newToken } from './sign'

const FOLLOW_UP_DAYS = 3

export function plansEnabled() {
  return plansConfigured() && emailConfigured() && Boolean(process.env.PLAN_SECRET)
}

/** Run from a form route after the lead is saved. Never throws. */
export async function startPlan(lead: LeadInput, opts: { booked?: boolean } = {}) {
  if (!plansEnabled() || !lead.email) return
  try {
    const token = newToken()
    const id = await createPlan(token, lead)
    if (opts.booked) await updatePlan(id, { 'Booked at': new Date().toISOString() })
    const { deck, by } = await generateDeck(lead)
    await updatePlan(id, { Plan: JSON.stringify(deck), 'Generated by': by, Status: 'Needs review' })
    const record = await findByToken(token)
    if (!record) return
    if (process.env.PLAN_AUTO_SEND === 'true') await sendPlan(record)
    else await sendReview(record)
  } catch (err) {
    console.error('startPlan failed:', err)
  }
}

function variantFor(p: PlanRecord): Variant {
  if (p.bookedAt) return 'booked'
  if (p.lead.source === 'Website in a Day' && !p.paidAt) return 'checkout'
  return 'invite'
}

export async function sendPlan(p: PlanRecord) {
  if (p.status !== 'Needs review' || !p.deck) return false
  const variant = variantFor(p)
  await sendPlanEmail(p, variant)
  const due = new Date(Date.now() + FOLLOW_UP_DAYS * 864e5).toISOString()
  await updatePlan(p.id, {
    Status: 'Sent', 'Sent at': new Date().toISOString(), Variant: variant,
    'Follow-up due': variant === 'booked' || !p.lead.consent ? null : due,
  })
  return true
}

export async function approvePlan(token: string) {
  const p = await findByToken(token)
  return p ? sendPlan(p) : false
}

/**
 * Cal.com booking: stop follow-ups; if the plan already went out as an invite,
 * send the pre-call version. No plan yet: build one from the booking answers.
 */
export async function markBooked(email: string, leadIfNew?: LeadInput) {
  if (!plansEnabled() || !email) return
  const p = await findLatestByEmail(email)
  if (!p) {
    if (leadIfNew) await startPlan(leadIfNew, { booked: true })
    return
  }
  await updatePlan(p.id, { 'Booked at': new Date().toISOString() })
  if (p.status === 'Sent' && p.variant !== 'booked') {
    await sendPlanEmail({ ...p, bookedAt: new Date().toISOString() }, 'booked')
    await updatePlan(p.id, { Variant: 'booked' })
  }
}

/** Stripe payment: stop follow-ups. */
export async function markPaid(email: string) {
  if (!plansEnabled() || !email) return
  const p = await findLatestByEmail(email)
  if (p) await updatePlan(p.id, { 'Paid at': new Date().toISOString() })
}

export async function markOpened(p: PlanRecord) {
  if (p.status === 'Sent' && !p.openedAt) await updatePlan(p.id, { 'Opened at': new Date().toISOString() })
}

export async function unsubscribe(p: PlanRecord) {
  await updatePlan(p.id, { Status: 'Unsubscribed', Consent: false })
}

/** Daily: send follow-ups that are due. */
export async function runFollowUps() {
  if (!plansEnabled()) return 0
  let sent = 0
  for (const p of await dueFollowUps()) {
    try {
      await sendFollowUp(p)
      await updatePlan(p.id, { 'Follow-up sent': new Date().toISOString() })
      sent++
    } catch (err) {
      console.error('Follow-up failed for', p.id, err)
    }
  }
  return sent
}
